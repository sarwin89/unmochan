"""Brillouin-zone meshes and the primitive k-points a supercell run resolves.

Why this exists
---------------

Two of the package's diagnostics -- the unfolded density of states
(:mod:`unfoldlab.core.dos`) and the Fermi level (:mod:`unfoldlab.core.fermi`) --
integrate over the Brillouin zone and therefore need a *mesh* of supercell
k-points rather than a band path.  The user then asks the question this module
answers: **given a supercell run on a k-mesh, which primitive k-points can I
unfold onto, and is the one I want among them?**

A *generalized regular mesh* is generated by an integer matrix ``M`` and a
fractional shift ``s``: the k-points ``k`` with ``M k = m + s`` for an integer
vector ``m``, i.e. ``k = M^-1 (m + s)``.  The Gamma-centred Monkhorst--Pack mesh
with divisions ``(n1, n2, n3)`` is ``M = diag(n)`` and ``s = 0``; the usual
half-shifted mesh is the same ``M`` with ``s = (1/2, 1/2, 1/2)``, which is also
the convention in which VASP writes its ``KPOINTS`` shift, namely in units of
one mesh spacing.

The mathematics is settled in ``RequestProject/Unfolding/Mesh.lean``:

*a mesh is a fiber*
    ``UnfoldLab.Mesh_eq_setOf_foldsTo``: the mesh generated by ``M`` with shift
    ``s`` is the set of k-points that ``M`` folds onto ``s``.  Every fiber
    theorem therefore applies, in particular that the mesh has ``|det M|``
    points and that the same Smith-normal-form enumeration produces them
    (:func:`unfoldlab.core.lattice_quotient.coset_representatives`);

*the unfolded mesh is the mesh of the product*
    ``UnfoldLab.unfoldedMesh_eq``: the primitive k-points folding onto some
    point of the supercell mesh ``M`` are exactly the points of the mesh
    ``M @ T``, with the *same* shift.  So there are ``|det M| * |det T|`` of
    them, one full fiber above each supercell k-point
    (``UnfoldLab.IsFiberRepr.mesh_fiber_complete``), which is the situation in
    which the weight sum rules are equalities rather than bounds;

*the shift is not scaled by the folding*
    ``UnfoldLab.zero_mem_Mesh_iff``: Gamma is on a mesh exactly when the shift
    is integral.  A half-shifted supercell mesh resolves no primitive k-point
    of the corresponding Gamma-centred mesh -- Gamma itself included -- for any
    transform whatsoever;

*an odd mesh never sees the zone boundary*
    ``UnfoldLab.zoneBoundary_mem_iff``: the point ``1/2 e_i`` is sampled exactly
    when the division along ``i`` is even;

*the unfolded mesh is generally not a Monkhorst--Pack mesh*
    ``UnfoldLab.exists_unfoldedMesh_not_product``: for a non-unimodular ``T``
    the generator ``M @ T`` is not diagonal and the point set is not a product
    of one-dimensional meshes, so no triple of divisions describes it.
    :func:`diagnose_mesh` reports this as ``is_product_mesh``; the k-points have
    to be enumerated, which is what :func:`unfolded_mesh_points` does;

*and a mesh has a resolution*
    ``UnfoldLab.mesh_resolution_bound``: a k-point at half the mesh spacing is
    that far from every mesh point.  :func:`mesh_distance` measures the error of
    substituting the nearest resolvable k-point for a requested one, using the
    certified minimum-image search of :mod:`unfoldlab.core.valleys` so that the
    number is a Cartesian distance and not a fractional one.
"""

